// Generates docs/SOURCES.md, docs/COVERAGE.md and docs/CONTENT_REVIEW.md from the site's own content data.
// Run with: npm run docs   (it is a no-op during normal test runs)
import { describe, it } from 'vitest';
import { mkdirSync, writeFileSync } from 'node:fs';
import { DOMAINS, LESSONS, MODULES, QUESTIONS, SERVICES } from '../content';
import { IN_SCOPE_SERVICES } from '../content/exam';
import { PRIMARY_SOURCES } from '../content/sources';
import { LIMITATIONS, REVIEW_LOG } from '../content/reviewlog';

const enabled = process.env.GENERATE_DOCS === '1';

describe.runIf(enabled)('generate docs', () => {
  it('writes the markdown registers', () => {
    mkdirSync('docs', { recursive: true });

    // SOURCES.md
    const refs = new Map<string, { title: string; lessons: string[] }>();
    for (const l of LESSONS) for (const r of l.references) {
      const e = refs.get(r.url) ?? { title: r.title, lessons: [] };
      e.lessons.push(l.id);
      refs.set(r.url, e);
    }
    let md = '# Source register\n\n> Generated by `npm run docs` from `src/content`. Do not edit by hand.\n\n## Primary sources\n\n| Source | Kind | What it supports |\n|---|---|---|\n';
    for (const s of PRIMARY_SOURCES) md += `| ${s.url ? `[${s.title}](${s.url})` : s.title + ' (local file supplied by the learner)'} | ${s.kind} | ${s.supports} |\n`;
    md += `\n## Lesson references (${refs.size} unique URLs)\n\n| Source | URL | Lessons that cite it |\n|---|---|---|\n`;
    for (const [url, e] of [...refs.entries()].sort((a, b) => a[1].title.localeCompare(b[1].title))) md += `| ${e.title.replace(/\|/g, '/')} | <${url}> | ${e.lessons.join(', ')} |\n`;
    writeFileSync('docs/SOURCES.md', md);

    // COVERAGE.md
    let cov = '# Syllabus coverage checklist\n\n> Generated by `npm run docs`. Official source: CLF-C02 exam guide (see SOURCES.md).\n\n';
    cov += `Totals: ${MODULES.length} modules, ${LESSONS.length} lessons, ${QUESTIONS.length} practice questions, ${SERVICES.length} directory entries.\n\n## Task statements\n\n| Task | Title | Lessons | Questions | Covered |\n|---|---|---|---|---|\n`;
    for (const d of DOMAINS) for (const t of d.taskStatements) {
      const ls = LESSONS.filter((l) => l.taskStatements.includes(t.id)).map((l) => l.id);
      const qn = QUESTIONS.filter((q) => q.taskStatement === t.id).length;
      cov += `| ${t.id} | ${t.title} | ${ls.join(', ')} | ${qn} | ${ls.length && qn >= 3 ? '[x]' : '[ ]'} |\n`;
    }
    cov += '\n## Official in-scope services\n\n';
    const have = new Set(SERVICES.map((s) => s.name));
    for (const [cat, names] of Object.entries(IN_SCOPE_SERVICES)) {
      cov += `### ${cat}\n\n` + names.map((n) => `- [${have.has(n) ? 'x' : ' '}] ${n}`).join('\n') + '\n\n';
    }
    cov += '## Services included that are not on the official in-scope list\n\n';
    cov += SERVICES.filter((s) => !s.inScope).map((s) => `- ${s.name} (${s.category}) — taught in \`${s.lessonId}\``).join('\n') + '\n';
    writeFileSync('docs/COVERAGE.md', cov);

    // CONTENT_REVIEW.md
    let rev = '# Content review checklist\n\n> Generated by `npm run docs` from `src/content/reviewlog.ts`.\n\nStatus legend: **verified** = checked against the cited official page; **partly** = checked in part or subject to rapid change; **unverified** = noted but not independently confirmed.\n\n| Area | Claim | Status | Source | Note |\n|---|---|---|---|---|\n';
    for (const e of REVIEW_LOG) rev += `| ${e.area} | ${e.claim} | ${e.status} | ${e.source} | ${e.note} |\n`;
    rev += '\n## Remaining limitations\n\n' + LIMITATIONS.map((l) => `- ${l}`).join('\n') + '\n';
    writeFileSync('docs/CONTENT_REVIEW.md', rev);
  });
});
